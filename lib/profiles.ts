export function matchProfile(name?: string | null): Profile | undefined {
  if (!name) return undefined;
  const n = name.replace(/\s+/g, "").replace(/^(Analyst|RA|연구원|연구위원)/i, "");
  return BY_NAME.get(n) ?? PROFILES.find((p) => n.includes(p.name));
}

